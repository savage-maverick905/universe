// Works out which files each app needs to open with no connection (its scripts, styles and icons) by following every
// import from the app's entry file, then writes that list into the app's sw.js. Run `npm run sw` after adding a file or a
// new import; `npm test` fails if a sw.js is out of date, so an app can never lose its offline screens by accident.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const APPS = [['dashboard', '/dashboard/'], ['finance', '/apps/finance/'], ['inventory', '/apps/inventory/'], ['jupiter', '/apps/jupiter/'], ['nova', '/apps/nova/'], ['pulsar', '/apps/pulsar/']];
const read = (url) => readFileSync(join(root, url), 'utf8');
const IMPORT = /(?:import|export)\s*(?:[^'"();]*?\sfrom\s*)?['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g;

export function crawl(base) {
  const files = new Set(), todo = [`${base}app.js`];
  while (todo.length) {
    const url = todo.pop(); if (files.has(url) || !existsSync(join(root, url))) continue;
    files.add(url);
    for (const m of read(url).matchAll(IMPORT)) {
      const spec = m[1] || m[2]; if (!spec.startsWith('.') && !spec.startsWith('/')) continue;
      todo.push(spec.startsWith('/') ? spec : posix.normalize(posix.join(posix.dirname(url), spec)));
    }
  }
  const html = read(`${base}index.html`), css = [...html.matchAll(/href="([^"]+\.css)"/g)].map((m) => m[1]);
  const icons = [`${base}icons/icon-192.png`, `${base}icons/icon.svg`].filter((u) => existsSync(join(root, u)));
  return [base, ...[...files].sort(), ...css, ...icons];
}

export const shellOf = (base) => [...new Set(crawl(base))];

export function swSource(id, base, version) {
  const shell = shellOf(base), lines = [];
  for (let i = 0; i < shell.length; i += 4) lines.push(`  ${shell.slice(i, i + 4).map((u) => `'${u}'`).join(', ')},`);
  return `// Offline screens: the files below are kept on the device so the app opens and navigates with no connection.\n// This list is generated by \`npm run sw\` (scripts/sw-shell.js). Data from /api/ is never cached. Bump the version when you deploy.\nself.UNIVERSE_SW = { prefix: 'universe-${id}', version: '${version}', shell: [\n${lines.join('\n')}\n] };\nimportScripts('/shared/sw-core.js');\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const version = process.argv[2] || 'v20-offline';
  for (const [id, base] of APPS) { writeFileSync(join(root, base, 'sw.js'), swSource(id, base, version)); console.log(`${base}sw.js  ${shellOf(base).length} files`); }
}
